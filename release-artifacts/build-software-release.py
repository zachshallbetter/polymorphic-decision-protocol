#!/usr/bin/env python3
"""Build a deterministic, manifest-controlled software release ZIP."""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import re
import shutil
import tempfile
from pathlib import Path, PurePosixPath

from package_archive import build_zip, sha256_file

REPOSITORY = Path(__file__).resolve().parents[1]
VERSION_PATTERN = re.compile(r"^v?(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$")
GENERATED_PATHS = {"metadata/manifest.csv", "archive/checksums.sha256"}
MANIFEST_FIELDS = ("path", "source", "description", "type", "license")
CHECKSUM_DESCRIPTION = "SHA-256 inventory of all package payload files"


def safe_path(value: str) -> PurePosixPath:
    path = PurePosixPath(value)
    if (
        not value
        or "\\" in value
        or ":" in value
        or "\x00" in value
        or path.is_absolute()
        or path.as_posix() != value
        or any(part in ("", ".", "..") for part in path.parts)
    ):
        raise ValueError(f"unsafe or non-canonical package path: {value!r}")
    return path


def read_manifest(source_root: Path, version: str) -> tuple[list[dict[str, str]], dict[str, str]]:
    manifest_path = source_root / "release-artifacts" / "manifests" / f"software-v{version}.csv"
    with manifest_path.open(encoding="utf-8", newline="") as stream:
        reader = csv.DictReader(stream)
        if tuple(reader.fieldnames or ()) != MANIFEST_FIELDS:
            raise ValueError(f"manifest header must be {','.join(MANIFEST_FIELDS)}")
        rows = list(reader)

    if not rows:
        raise ValueError("software manifest is empty")

    output_paths: set[str] = set()
    normalized_paths: set[str] = set()
    files: list[dict[str, str]] = []
    manifest_entry = None
    for row in rows:
        if None in row or any(not (row.get(field) or "").strip() for field in MANIFEST_FIELDS):
            raise ValueError("software manifest has an unexpected column or a blank required field")
        output = safe_path(row["path"].strip()).as_posix()
        source = safe_path(row["source"].strip())
        if output in output_paths:
            raise ValueError(f"duplicate package path: {output}")
        if output.casefold() in normalized_paths:
            raise ValueError(f"package path collides on a case-insensitive filesystem: {output}")
        output_paths.add(output)
        normalized_paths.add(output.casefold())

        if output == "metadata/manifest.csv":
            if source.as_posix() != f"release-artifacts/manifests/software-v{version}.csv":
                raise ValueError("metadata/manifest.csv must reference the version-matched source manifest")
            manifest_entry = row
            continue
        if output in GENERATED_PATHS:
            raise ValueError(f"{output} is generated by the builder and must not be a source entry")
        if output.startswith(".agents/") or PurePosixPath(output).name.startswith("llms"):
            raise ValueError(f"generated LLM corpus is outside the software release boundary: {output}")

        source_path = source_root.joinpath(*source.parts)
        if any(part.is_symlink() for part in (source_path, *source_path.parents) if part != source_root.parent):
            raise ValueError(f"symlinked manifest source is not allowed: {source.as_posix()}")
        resolved = source_path.resolve(strict=True)
        if not resolved.is_relative_to(source_root) or not resolved.is_file():
            raise ValueError(f"manifest source is missing or outside the source tree: {source.as_posix()}")

        files.append({
            "path": output,
            "source": source.as_posix(),
            "description": row["description"].strip(),
            "type": row["type"].strip(),
            "license": row["license"].strip(),
        })

    if manifest_entry is None:
        raise ValueError("software manifest must include metadata/manifest.csv")
    for output in output_paths:
        parent = PurePosixPath(output).parent
        while parent != PurePosixPath("."):
            if parent.as_posix() in output_paths:
                raise ValueError(f"package path is both a file and a directory: {parent.as_posix()}")
            parent = parent.parent
    if "llms.txt" in output_paths or "llms-full.txt" in output_paths:
        raise ValueError("generated LLM corpus files must not be included in the software archive")
    return files, manifest_entry


def write_package_manifest(package_root: Path, files: list[dict[str, str]], manifest_entry: dict[str, str]) -> None:
    manifest_path = package_root / "metadata" / "manifest.csv"
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    entries = [
        (entry["path"], entry["description"], entry["type"], entry["license"])
        for entry in files
    ]
    entries.extend([
        ("metadata/manifest.csv", manifest_entry["description"].strip(), manifest_entry["type"].strip(), manifest_entry["license"].strip()),
        ("archive/checksums.sha256", CHECKSUM_DESCRIPTION, "archive", "MIT"),
    ])
    with manifest_path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerow(("path", "description", "type", "license"))
        writer.writerows(sorted(entries, key=lambda row: row[0]))


def write_checksums(package_root: Path) -> None:
    checksum_path = package_root / "archive" / "checksums.sha256"
    checksum_path.parent.mkdir(parents=True, exist_ok=True)
    files = sorted(path for path in package_root.rglob("*") if path.is_file() and path != checksum_path)
    with checksum_path.open("w", encoding="utf-8", newline="") as stream:
        for path in files:
            relative = path.relative_to(package_root).as_posix()
            stream.write(f"{sha256_file(path)}  {relative}\n")


def verify_package(package_root: Path, version: str) -> set[str]:
    files = {path.relative_to(package_root).as_posix() for path in package_root.rglob("*") if path.is_file()}
    with (package_root / "metadata" / "manifest.csv").open(encoding="utf-8", newline="") as stream:
        listed = {row["path"] for row in csv.DictReader(stream)}
    if listed != files:
        raise ValueError("package manifest does not exactly match the package file list")

    checksum_path = package_root / "archive" / "checksums.sha256"
    checked: set[str] = set()
    with checksum_path.open(encoding="utf-8") as stream:
        for line in stream:
            expected_hash, relative = line.rstrip("\n").split("  ", maxsplit=1)
            path = safe_path(relative)
            candidate = package_root.joinpath(*path.parts)
            if not candidate.is_file() or sha256_file(candidate) != expected_hash:
                raise ValueError(f"package checksum mismatch: {relative}")
            checked.add(relative)
    if checked != files - {"archive/checksums.sha256"}:
        raise ValueError("package checksum inventory does not exactly match package contents")

    metadata = json.loads((package_root / ".zenodo.json").read_text(encoding="utf-8"))
    if metadata.get("version") != version:
        raise ValueError(".zenodo.json version does not match the release tag")
    citation = (package_root / "CITATION.cff").read_text(encoding="utf-8")
    if re.search(rf'(?m)^version:\s*["\']?{re.escape(version)}["\']?\s*$', citation) is None:
        raise ValueError("CITATION.cff version does not match the release tag")
    readme = (package_root / "README.md").read_text(encoding="utf-8")
    if re.search(rf"(?m)^- \*\*Package:\*\* PDP Local Toolkit {re.escape(version)}$", readme) is None:
        raise ValueError("software README package version does not match the release tag")
    if metadata.get("title") != "Polymorphic Decision Protocol":
        raise ValueError(".zenodo.json title does not match the package title")
    return files


def build(tag: str, source_root: Path, output_dir: Path) -> tuple[Path, Path]:
    match = VERSION_PATTERN.fullmatch(tag)
    if match is None:
        raise ValueError("release tag must be vMAJOR.MINOR.PATCH or MAJOR.MINOR.PATCH")
    version = ".".join(match.groups())
    source_root = source_root.resolve(strict=True)
    rows, manifest_entry = read_manifest(source_root, version)

    prefix = f"PDP-software-v{version}"
    output_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="pdp-software-package-") as temporary:
        package_root = Path(temporary) / prefix
        package_root.mkdir()
        for entry in rows:
            source = safe_path(entry["source"])
            source_path = source_root.joinpath(*source.parts).resolve(strict=True)
            destination = package_root.joinpath(*PurePosixPath(entry["path"]).parts)
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source_path, destination)

        write_package_manifest(package_root, rows, manifest_entry)
        write_checksums(package_root)
        expected = verify_package(package_root, version)
        return build_zip(package_root, prefix, output_dir, expected)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tag", help="GitHub release tag, for example v1.4.0")
    parser.add_argument("--source-dir", type=Path, default=REPOSITORY, help="extracted source tree for the release tag")
    parser.add_argument("--output-dir", type=Path, required=True, help="directory for the ZIP and its SHA-256 file")
    args = parser.parse_args()
    zip_path, checksum_path = build(args.tag, args.source_dir, args.output_dir)
    print(f"{zip_path} ({zip_path.stat().st_size} bytes)")
    print(checksum_path.read_text(encoding="utf-8"), end="")


if __name__ == "__main__":
    main()
